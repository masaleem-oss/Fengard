// package features installs and removes add-ons, the parts of Fengard a router can do without.
// the go code for each one stays in fengardd since it's tiny, what gets downloaded is the
// dashboard pages and data that make up most of an add-on's size
package features

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"context"
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
	"sync"
	"time"
)

type File struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
	Size   int64  `json:"size"`
}

// what the release ships for one add-on, generated by tools/featurepack
type Pack struct {
	ID       string `json:"id"`
	Files    []File `json:"files"`
	Download int64  `json:"download"` // bytes of feature-<id>.tar.gz
}

//go:embed manifest.json
var manifestJSON []byte

var Packs = func() []Pack {
	var p []Pack
	if err := json.Unmarshal(manifestJSON, &p); err != nil {
		panic(err)
	}
	return p
}()

func Find(id string) *Pack {
	for i := range Packs {
		if Packs[i].ID == id {
			return &Packs[i]
		}
	}
	return nil
}

func Archive(id string) string { return "feature-" + id + ".tar.gz" }

type Info struct {
	ID       string `json:"id"`
	Wanted   bool   `json:"wanted"`
	Ready    bool   `json:"ready"`
	Busy     bool   `json:"busy"`
	Error    string `json:"error,omitempty"`
	Download int64  `json:"download"`
	Disk     int64  `json:"disk"`
}

type Manager struct {
	Dir string // installed add-ons, one folder each
	// tried in order, a folder holding feature-<id>.tar.gz or <id>/ or a url ending in /
	Sources []string
	Client  *http.Client
	Wanted  func() []string
	// called after an add-on's files appear or go
	OnChange func(id string, ready bool)

	mu    sync.Mutex
	state map[string]*status
	kick  chan struct{}
}

type status struct {
	ready, busy bool
	err         string
}

func (m *Manager) init() {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.state == nil {
		m.state = map[string]*status{}
		for _, p := range Packs {
			m.state[p.ID] = &status{}
		}
		m.kick = make(chan struct{}, 1)
	}
}

// Check looks at what's on disk without downloading anything, run it before the dashboard starts
func (m *Manager) Check() {
	m.init()
	for _, p := range Packs {
		ok := verify(filepath.Join(m.Dir, p.ID), &p) == nil
		m.mu.Lock()
		m.state[p.ID].ready = ok
		m.mu.Unlock()
	}
}

func (m *Manager) Kick() {
	m.init()
	select {
	case m.kick <- struct{}{}:
	default:
	}
}

// Run installs what's wanted and removes what isn't, trying again every 10 minutes
// while something couldn't be downloaded
func (m *Manager) Run(ctx context.Context) {
	m.init()
	m.reconcile(ctx)
	t := time.NewTicker(10 * time.Minute)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
		case <-m.kick:
		}
		m.reconcile(ctx)
	}
}

func (m *Manager) reconcile(ctx context.Context) {
	m.init()
	want := m.Wanted()
	for _, p := range Packs {
		if ctx.Err() != nil {
			return
		}
		dir := filepath.Join(m.Dir, p.ID)
		m.mu.Lock()
		st := m.state[p.ID]
		ready := st.ready
		m.mu.Unlock()
		if !slices.Contains(want, p.ID) {
			if _, err := os.Stat(dir); err == nil {
				os.RemoveAll(dir)
				log.Printf("add-ons: removed %s", p.ID)
			}
			m.set(p.ID, false, "")
			if ready {
				m.changed(p.ID, false)
			}
			continue
		}
		// a newer release can change an add-on's files, so check them every time
		if verify(dir, &p) == nil {
			m.set(p.ID, true, "")
			if !ready {
				m.changed(p.ID, true)
			}
			continue
		}
		m.mu.Lock()
		st.busy = true
		m.mu.Unlock()
		err := m.install(ctx, &p)
		m.mu.Lock()
		st.busy = false
		m.mu.Unlock()
		if err != nil {
			log.Printf("add-ons: %s: %v", p.ID, err)
			// the old files keep working until the new ones arrive
			m.set(p.ID, ready, err.Error())
			continue
		}
		log.Printf("add-ons: installed %s", p.ID)
		m.set(p.ID, true, "")
		m.changed(p.ID, true)
	}
}

func (m *Manager) set(id string, ready bool, err string) {
	m.mu.Lock()
	defer m.mu.Unlock()
	m.state[id].ready, m.state[id].err = ready, err
}

func (m *Manager) changed(id string, ready bool) {
	if m.OnChange != nil {
		m.OnChange(id, ready)
	}
}

func (m *Manager) Ready(id string) bool {
	m.init()
	m.mu.Lock()
	defer m.mu.Unlock()
	st := m.state[id]
	return st != nil && st.ready
}

// Path is where an installed add-on's file is, only meaningful while it's Ready
func (m *Manager) Path(id, file string) string {
	return filepath.Join(m.Dir, id, filepath.FromSlash(file))
}

func (m *Manager) List() []Info {
	m.init()
	want := m.Wanted()
	m.mu.Lock()
	defer m.mu.Unlock()
	var out []Info
	for _, p := range Packs {
		st := m.state[p.ID]
		inf := Info{ID: p.ID, Wanted: slices.Contains(want, p.ID), Ready: st.ready, Busy: st.busy, Error: st.err, Download: p.Download}
		for _, f := range p.Files {
			inf.Disk += f.Size
		}
		out = append(out, inf)
	}
	return out
}

var errNoSource = errors.New("no download source")

func (m *Manager) install(ctx context.Context, p *Pack) error {
	tmp := filepath.Join(m.Dir, ".new-"+p.ID)
	os.RemoveAll(tmp)
	defer os.RemoveAll(tmp)
	err := errNoSource
	for _, src := range m.Sources {
		if src == "" {
			continue
		}
		os.RemoveAll(tmp)
		if err = m.fetch(ctx, src, p, tmp); err == nil {
			if err = verify(tmp, p); err == nil {
				break
			}
		}
	}
	if err != nil {
		if errors.Is(err, errNoSource) {
			return errors.New("couldn't find it, it downloads once the router is online")
		}
		return err
	}
	dir := filepath.Join(m.Dir, p.ID)
	old := filepath.Join(m.Dir, ".old-"+p.ID)
	os.RemoveAll(old)
	if _, err := os.Stat(dir); err == nil {
		if err := os.Rename(dir, old); err != nil {
			return err
		}
	}
	if err := os.Rename(tmp, dir); err != nil {
		os.Rename(old, dir)
		return err
	}
	os.RemoveAll(old)
	return nil
}

func (m *Manager) fetch(ctx context.Context, src string, p *Pack, to string) error {
	if strings.HasPrefix(src, "http://") || strings.HasPrefix(src, "https://") {
		ctx, cancel := context.WithTimeout(ctx, 2*time.Minute)
		defer cancel()
		req, err := http.NewRequestWithContext(ctx, http.MethodGet, src+Archive(p.ID), nil)
		if err != nil {
			return err
		}
		c := m.Client
		if c == nil {
			c = http.DefaultClient
		}
		resp, err := c.Do(req)
		if err != nil {
			return fmt.Errorf("download failed: %v", err)
		}
		defer resp.Body.Close()
		if resp.StatusCode == http.StatusNotFound {
			return errNoSource
		}
		if resp.StatusCode != http.StatusOK {
			return fmt.Errorf("download failed: %s", resp.Status)
		}
		return extract(io.LimitReader(resp.Body, 16<<20), p, to)
	}
	if f, err := os.Open(filepath.Join(src, Archive(p.ID))); err == nil {
		defer f.Close()
		return extract(f, p, to)
	}
	// a source tree, how dev runs get their add-ons
	if _, err := os.Stat(filepath.Join(src, p.ID)); err != nil {
		return errNoSource
	}
	for _, f := range p.Files {
		b, err := os.ReadFile(filepath.Join(src, p.ID, filepath.FromSlash(f.Path)))
		if err != nil {
			return err
		}
		if !strings.HasSuffix(f.Path, ".gz") {
			b = bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n"))
		}
		if err := write(to, f.Path, b); err != nil {
			return err
		}
	}
	return nil
}

// only files the manifest names come out of the archive, whatever else is in it is skipped
func extract(r io.Reader, p *Pack, to string) error {
	zr, err := gzip.NewReader(r)
	if err != nil {
		return err
	}
	tr := tar.NewReader(zr)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return nil
		}
		if err != nil {
			return err
		}
		i := slices.IndexFunc(p.Files, func(f File) bool { return f.Path == h.Name })
		if i < 0 || h.Typeflag != tar.TypeReg {
			continue
		}
		b, err := io.ReadAll(io.LimitReader(tr, p.Files[i].Size+1))
		if err != nil {
			return err
		}
		if err := write(to, h.Name, b); err != nil {
			return err
		}
	}
}

func write(dir, name string, b []byte) error {
	if !cleanName(name) {
		return fmt.Errorf("odd file name %q", name)
	}
	p := filepath.Join(dir, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, b, 0o644)
}

// a plain relative path with no way out of the add-on's folder
func cleanName(name string) bool {
	return name != "" && path.Clean(name) == name && !path.IsAbs(name) && !strings.HasPrefix(name, "..") && !strings.Contains(name, "\\")
}

func verify(dir string, p *Pack) error {
	for _, f := range p.Files {
		b, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(f.Path)))
		if err != nil {
			return err
		}
		if sum := sha256.Sum256(b); hex.EncodeToString(sum[:]) != f.SHA256 {
			return fmt.Errorf("%s doesn't match this version of Fengard", f.Path)
		}
	}
	return nil
}

// Scan describes the add-ons in a source tree, the release and the manifest both come from this
func Scan(src string, ids []string) ([]Pack, error) {
	var out []Pack
	for _, id := range ids {
		p := Pack{ID: id}
		root := filepath.Join(src, id)
		err := filepath.WalkDir(root, func(fp string, d os.DirEntry, err error) error {
			if err != nil || d.IsDir() {
				return err
			}
			b, err := os.ReadFile(fp)
			if err != nil {
				return err
			}
			// git on windows can hand out crlf copies, the release always ships lf
			if !strings.HasSuffix(fp, ".gz") {
				b = bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n"))
			}
			rel, _ := filepath.Rel(root, fp)
			sum := sha256.Sum256(b)
			p.Files = append(p.Files, File{Path: filepath.ToSlash(rel), SHA256: hex.EncodeToString(sum[:]), Size: int64(len(b))})
			return nil
		})
		if err != nil {
			return nil, err
		}
		if len(p.Files) == 0 {
			return nil, fmt.Errorf("add-on %s has no files", id)
		}
		a, err := Build(src, &p)
		if err != nil {
			return nil, err
		}
		p.Download = int64(len(a))
		out = append(out, p)
	}
	return out, nil
}

// Build makes feature-<id>.tar.gz the same way every time
func Build(src string, p *Pack) ([]byte, error) {
	var buf bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	tw := tar.NewWriter(zw)
	for _, f := range p.Files {
		b, err := os.ReadFile(filepath.Join(src, p.ID, filepath.FromSlash(f.Path)))
		if err != nil {
			return nil, err
		}
		if !strings.HasSuffix(f.Path, ".gz") {
			b = bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n"))
		}
		if err := tw.WriteHeader(&tar.Header{Name: f.Path, Mode: 0o644, Size: int64(len(b)), ModTime: time.Unix(0, 0), Typeflag: tar.TypeReg, Format: tar.FormatUSTAR}); err != nil {
			return nil, err
		}
		tw.Write(b)
	}
	if err := tw.Close(); err != nil {
		return nil, err
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
